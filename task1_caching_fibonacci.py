"""
ЗАВДАННЯ 1: КЕШИРОВАНА ФУНКЦІЯ ФІБОНАЧЧІ

Це програма використовує замикання (closure) для створення кешу.
Замикання дозволяє функції "пам'ятати" змінну cache між викликами.

Що це робить:
- Обчислює числа Фібоначчі за допомогою рекурсії
- Зберігає результати в кеш для швидшого обчислення
- Вже обчислені числа не розраховуються ще раз
"""


def caching_fibonacci():
    """
    Зовнішня функція, яка створює локальний словник cache.
    Повертає внутрішню функцію fibonacci.
    
    Це приклад замикання - fibonacci "пам'ятає" cache між викликами.
    """
    # cache - локальна змінна зовнішної функції
    # Внутрішня функція "видить" і використовує цю змінну
    cache = {}
    
    def fibonacci(n):
        """
        Внутрішня функція обчислює n-те число Фібоначчі.
        
        Як працює:
        1. Якщо n <= 0, повертаємо 0
        2. Якщо n == 1, повертаємо 1
        3. Якщо число вже в кеші - повертаємо його негайно (швидко!)
        4. Якщо числа немає в кеші - обчислюємо рекурсивно і зберігаємо
        
        Формула Фібоначчі: F(n) = F(n-1) + F(n-2)
        """
        
        # Базові випадки
        if n <= 0:
            return 0
        if n == 1:
            return 1
        
        # Якщо число вже обчислено, беремо його з кешу (це швидко!)
        if n in cache:
            return cache[n]
        
        # Якщо числа немає в кеші - обчислюємо його
        # Викликаємо fibonacci(n-1) та fibonacci(n-2), результати беруться з кешу
        cache[n] = fibonacci(n - 1) + fibonacci(n - 2)
        
        # Повертаємо результат
        return cache[n]
    
    # Повертаємо внутрішню функцію
    # Вона "залишається" з власним cache словником
    return fibonacci


# ============== ПРИКЛАДИ ВИКОРИСТАННЯ ==============

# Отримуємо функцію fibonacci
fib = caching_fibonacci()

# Обчислюємо 10-те число Фібоначчі
result1 = fib(10)
print(f"fib(10) = {result1}")  # Виведе 55

# Обчислюємо 15-те число Фібоначчі
# При цьому багато значень уже в кеші, тому обчислення швидше
result2 = fib(15)
print(f"fib(15) = {result2}")  # Виведе 610

# Можемо продовжити з іншими числами
result3 = fib(20)
print(f"fib(20) = {result3}")  # Виведе 6765

print("\n✓ Програма завершена успішно!")
